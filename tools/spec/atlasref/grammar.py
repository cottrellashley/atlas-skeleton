"""§9.1.3–§9.1.5: every identifier, version, address, fingerprint, date, time,
duration, decimal and large-integer grammar, with the prose constraints the
sections add to their ABNF.

Two independent readings of the same grammars live in this package: the
matchers below (regular expressions plus the prose checks, written from the
text), and `abnf.py`, which parses `ABNF` (the text of `references/grammar.abnf`)
and matches it directly. The grammar vectors are generated from the matchers
and checked against the ABNF engine.
"""

import re

# The file references/grammar.abnf, written verbatim by the generator.
ABNF = """\
; references/grammar.abnf: the grammars of the Atlas Protocol, atlas/1.0.
; Generated by tools/spec (python -m atlasref write) from the text of the Atlas
; spec; do not edit by hand. The text is normative; this file transcribes it.
;
; ABNF (RFC 5234) with RFC 7405's %s"..." for case-sensitive strings. Every
; Atlas grammar is case-sensitive (§9.1.1): no quoted string below holds a
; letter unless it is written %s"...". ALPHA, DIGIT, HEXDIG, DQUOTE and SP are
; RFC 5234's core rules (Appendix B.1).
;
; Two rules encode in ABNF a sentence the text adds to its rule, and quote the
; text's own form beside them: segment ("a segment never ends with -, and never
; contains --") and duration ("P alone is not allowed; at least one component
; is present"). What ABNF cannot express is written as a "constraint:" comment
; under its rule. references/vectors/grammar.json tests both.

; ---------------------------------------------------------------------------
; §9.1.3 Identifiers

segment       = %x61-7A *( %x61-7A / DIGIT / "-" %x61-7A / "-" DIGIT )
                ; a-z first, then a-z 0-9 -.
                ; §9.1.3: segment = %x61-7A *( %x61-7A / DIGIT / "-" ), and "a
                ; segment never ends with -, and never contains --".
capability-id = segment 1*( "." segment )              ; portfolio.holdings, atlas.whoami
                ; constraint: at most 128 characters.
                ; constraint: one whose domain is "atlas" names a built-in (§9.3.2).
domain        = segment                                ; the first segment of a capability-id
version       = %s"v" nz-digits                        ; v1, v12
nz-digits     = %x31-39 *DIGIT
interaction   = segment                                ; fetch, get, restart
fingerprint   = 16( DIGIT / %x61-66 )                  ; 16 lowercase hexadecimal characters
pinned-id     = capability-id "@" version              ; portfolio.holdings@v1
exact-id      = pinned-id "#" fingerprint              ; portfolio.holdings@v1#3f9a1c0b7d2e4a65
address       = ( capability-id / pinned-id ) ":" interaction
                ; portfolio.holdings@v1:fetch
                ; constraint: at most 160 characters.
protocol-ver  = %s"atlas/" 1*DIGIT "." 1*DIGIT         ; atlas/1.0
property-name = %x61-7A *( %x61-7A / DIGIT / "_" )     ; snake_case, in every schema
problem-code  = %x61-7A *( %x61-7A / DIGIT / "_" )     ; not_found, limit_exceeded

; ---------------------------------------------------------------------------
; §9.1.4 Dates, times and durations

date          = 4DIGIT "-" 2DIGIT "-" 2DIGIT           ; RFC 3339 full-date
                ; constraint: a real calendar date (proleptic Gregorian):
                ; month 01-12, day 01 to the month's last day.
date-time     = date %s"T" 2DIGIT ":" 2DIGIT ":" 2DIGIT [ "." 1*9DIGIT ]
                ( %s"Z" / ( "+" / "-" ) 2DIGIT ":" 2DIGIT )
                ; constraint: a real instant: a real date; hour 00-23, minute
                ; 00-59, second 00-59 (the leap second 60 is not allowed); an
                ; offset's hours 00-23 and minutes 00-59. A receiver truncates
                ; a fraction to its own precision, never rounding.
duration      = %s"P" ( dur-day [ %s"T" [ dur-hour ] [ dur-minute ] [ dur-second ] ]
                      / %s"T" dur-time )
dur-time      = dur-hour [ dur-minute ] [ dur-second ] / dur-minute [ dur-second ] / dur-second
dur-day       = 1*DIGIT %s"D"
dur-hour      = 1*DIGIT %s"H"
dur-minute    = 1*DIGIT %s"M"
dur-second    = 1*DIGIT [ "." 1*9DIGIT ] %s"S"
                ; §9.1.4: duration = %s"P" [ 1*DIGIT %s"D" ] [ %s"T" [ 1*DIGIT %s"H" ]
                ; [ 1*DIGIT %s"M" ] [ 1*DIGIT [ "." 1*9DIGIT ] %s"S" ] ], and "P alone
                ; is not allowed; at least one component is present". Days,
                ; hours, minutes and seconds only; one day is 86400 seconds.

; ---------------------------------------------------------------------------
; §9.1.5 Decimals and large integers

decimal       = [ "-" ] ( "0" / nz-digits ) [ "." 1*DIGIT ]
                ; constraint: no negative zero ("-0", "-0.0", ...).
                ; constraint: with Decimal(p,s), at most s digits after the
                ; point and at most p digits in all once the integer part is
                ; written without leading zeros and the fraction is padded to s
                ; digits (QUESTIONS.md, Q-DEC-1).
integer-str   = [ "-" ] ( "0" / nz-digits )

; ---------------------------------------------------------------------------
; Strings the protocol defines in prose outside §9.1, collected so that every
; string that crosses the wire has a grammar. Each names its source. Those
; marked PROVISIONAL are not in the text: they are choices recorded in
; QUESTIONS.md until the spec settles them.

idempotency-key = 1*255( ALPHA / DIGIT / "-" / "_" / "." )          ; §9.6.3
problem-type    = %s"https://atlas.jhg.com/problems/" problem-code   ; §9.3.3
dataschema      = %s"urn:atlas:profile:" pinned-id ":" fingerprint   ; §9.4.3
event-type      = %s"com.jhg.fiquant." capability-id %s".v" nz-digits
                ; §2.5 and §3.3.7: com.jhg.fiquant.data.landed.v1 for data.landed@v1
resource-name   = domain 1*( "/" segment "/" resource-id )
                ; §9.3.4 names "resource-name in the grammar"; §9.1 has none.
                ; PROVISIONAL (Q-GRAM-1): nautilus/dashboards/d1
resource-id     = ( %x61-7A / DIGIT ) *( %x61-7A / DIGIT / "-" )    ; PROVISIONAL (Q-GRAM-1)
operation-name  = %s"operations/" resource-id
                ; §4.1: operations/{id}. PROVISIONAL (Q-GRAM-1)
entity-tag      = [ %s"W/" ] DQUOTE *etagc DQUOTE
                ; RFC 9110 section 8.8.3, as an ETag is written in a document
                ; (metadata.etag, catalog_etag): "\\"e8\\"".
etagc           = %x21 / %x23-7E
                ; RFC 9110's obs-text is left out: a document's ETag is ASCII.
"""

# The rules of §9.1.3–§9.1.5, in the order the text gives them, then the rest.
SPEC_RULES = [
    "segment", "capability-id", "domain", "version", "nz-digits", "interaction", "fingerprint",
    "pinned-id", "exact-id", "address", "protocol-ver", "property-name", "problem-code",
    "date", "date-time", "duration", "decimal", "integer-str",
]
EXTRA_RULES = [
    "idempotency-key", "problem-type", "dataschema", "event-type", "resource-name", "resource-id",
    "operation-name", "entity-tag",
]
PROVISIONAL = {"resource-name", "resource-id", "operation-name"}

_SEG = r"[a-z](?:-?[a-z0-9])*"
_CAP = _SEG + r"(?:\." + _SEG + r")+"
_VER = r"v[1-9][0-9]*"
_FP = r"[0-9a-f]{16}"
_PIN = _CAP + "@" + _VER
_DATE = r"([0-9]{4})-([0-9]{2})-([0-9]{2})"
_RID = r"[a-z0-9][a-z0-9-]*"

_RE = {
    "segment": _SEG,
    "capability-id": _CAP,
    "domain": _SEG,
    "version": _VER,
    "nz-digits": r"[1-9][0-9]*",
    "interaction": _SEG,
    "fingerprint": _FP,
    "pinned-id": "(" + _CAP + ")@" + _VER,
    "exact-id": "(" + _CAP + ")@" + _VER + "#" + _FP,
    "address": "(" + _CAP + ")(?:@" + _VER + ")?:" + _SEG,
    "protocol-ver": r"atlas/[0-9]+\.[0-9]+",
    "property-name": r"[a-z][a-z0-9_]*",
    "problem-code": r"[a-z][a-z0-9_]*",
    "date": _DATE,
    "date-time": _DATE + r"T([0-9]{2}):([0-9]{2}):([0-9]{2})(?:\.([0-9]{1,9}))?(?:Z|[+-]([0-9]{2}):([0-9]{2}))",
    "duration": r"P(?:([0-9]+)D)?(?:T(?:([0-9]+)H)?(?:([0-9]+)M)?(?:([0-9]+)(?:\.([0-9]{1,9}))?S)?)?",
    "decimal": r"-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?",
    "integer-str": r"-?(?:0|[1-9][0-9]*)",
    "idempotency-key": r"[A-Za-z0-9._-]{1,255}",
    "problem-type": r"https://atlas\.jhg\.com/problems/[a-z][a-z0-9_]*",
    "dataschema": "urn:atlas:profile:(" + _CAP + ")@" + _VER + ":" + _FP,
    "event-type": r"com\.jhg\.fiquant\.(" + _CAP + r")\.v[1-9][0-9]*",
    "resource-name": _SEG + "(?:/" + _SEG + "/" + _RID + ")+",
    "resource-id": _RID,
    "operation-name": "operations/" + _RID,
    "entity-tag": r'(?:W/)?"[\x21\x23-\x7e]*"',
}
_COMPILED = {k: re.compile(v) for k, v in _RE.items()}

RULES = SPEC_RULES + EXTRA_RULES


def leap(year):
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def days_in_month(year, month):
    if month == 2:
        return 29 if leap(year) else 28
    return 30 if month in (4, 6, 9, 11) else 31


def real_date(y, m, d):
    return 1 <= m <= 12 and 1 <= d <= days_in_month(y, m)


def check(rule, s):
    """Returns None when `s` is a value of `rule`, else why it is not: "abnf"
    (the ABNF refuses it), or the sentence of the text that does."""
    if not isinstance(s, str):
        return "abnf"
    m = _COMPILED[rule].fullmatch(s)
    if not m:
        return "abnf"
    if rule == "capability-id" and len(s) > 128:
        return "length: a capability id is at most 128 characters"
    if rule in ("pinned-id", "exact-id", "dataschema", "event-type") and len(m.group(1)) > 128:
        return "length: a capability id is at most 128 characters"
    if rule == "address":
        if len(m.group(1)) > 128:
            return "length: a capability id is at most 128 characters"
        if len(s) > 160:
            return "length: an address is at most 160 characters"
    if rule == "date":
        if not real_date(int(m.group(1)), int(m.group(2)), int(m.group(3))):
            return "calendar: not a real calendar date"
    if rule == "date-time":
        y, mo, d, hh, mi, ss = (int(m.group(i)) for i in range(1, 7))
        if not real_date(y, mo, d):
            return "calendar: not a real calendar date"
        if ss == 60:
            return "clock: the leap second 60 is not allowed"
        if hh > 23 or mi > 59 or ss > 59:
            return "clock: not a real time of day"
        if m.group(8) is not None and (int(m.group(8)) > 23 or int(m.group(9)) > 59):
            return "clock: not a real offset"
    if rule == "duration":
        if not any(m.group(i) is not None for i in (1, 2, 3, 4)):
            return "abnf"  # "P alone is not allowed": encoded in the ABNF itself
    if rule == "decimal" and s.startswith("-") and set(s[1:]) <= {"0", "."}:
        return "negative-zero: -0 is not allowed"
    return None


def matches(rule, s):
    return check(rule, s) is None


# --- values -----------------------------------------------------------------


def parse_date(s):
    """(year, month, day) of a valid `date`, else None."""
    if not matches("date", s):
        return None
    return int(s[0:4]), int(s[5:7]), int(s[8:10])


def days_from_civil(y, m, d):
    """Days since 1970-01-01 of a proleptic Gregorian date (H. Hinnant)."""
    y -= m <= 2
    era = (y if y >= 0 else y - 399) // 400
    yoe = y - era * 400
    doy = (153 * (m + (-3 if m > 2 else 9)) + 2) // 5 + d - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468


def civil_from_days(z):
    z += 719468
    era = (z if z >= 0 else z - 146096) // 146097
    doe = z - era * 146097
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    y = yoe + era * 400
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = mp + (3 if mp < 10 else -9)
    return y + (m <= 2), m, d


def parse_date_time_ns(s):
    """A valid `date-time` as nanoseconds since the epoch (UTC), else None."""
    if not matches("date-time", s):
        return None
    m = _COMPILED["date-time"].fullmatch(s)
    y, mo, d, hh, mi, ss = (int(m.group(i)) for i in range(1, 7))
    frac = (m.group(7) or "").ljust(9, "0")
    seconds = days_from_civil(y, mo, d) * 86400 + hh * 3600 + mi * 60 + ss
    if m.group(8) is not None:
        offset = int(m.group(8)) * 3600 + int(m.group(9)) * 60
        seconds -= offset if s[-6] == "+" else -offset
    return seconds * 1_000_000_000 + int(frac)


def format_date(days):
    y, m, d = civil_from_days(days)
    return f"{y:04d}-{m:02d}-{d:02d}"


def format_date_time_us(us):
    """The canonical RFC 3339 form of a microsecond instant used in every
    reference file: UTC, `Z`, exactly six fractional digits (Q-TIME-1)."""
    seconds, micros = divmod(us, 1_000_000)
    days, rem = divmod(seconds, 86400)
    hh, rem = divmod(rem, 3600)
    mi, ss = divmod(rem, 60)
    return f"{format_date(days)}T{hh:02d}:{mi:02d}:{ss:02d}.{micros:06d}Z"


def parse_duration_us(s):
    """A valid `duration` in microseconds, the fraction truncated."""
    if not matches("duration", s):
        return None
    m = _COMPILED["duration"].fullmatch(s)
    days, hours, minutes, secs = (int(m.group(i) or 0) for i in (1, 2, 3, 4))
    frac = (m.group(5) or "").ljust(9, "0")
    total = ((days * 24 + hours) * 60 + minutes) * 60 + secs
    return total * 1_000_000 + int(frac) // 1000
