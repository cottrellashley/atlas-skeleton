// Command reqs keeps the requirement matrix: every requirement of the spec
// (ATLAS-*, AP-*) and what proves it.
//
//	reqs index  -spec <atlas-spec dir>     writes spec/requirements.json from the spec
//	reqs report [-strict] [-o file]        maps each requirement to the tests naming it
//
// A test proves a requirement by naming its id in the test file, in a comment
// or a test name. A requirement checked by review instead is listed, with the
// review's record, in spec/review.toml. report also checks ATLAS-PRINCIPLES-002:
// every principle names at least one requirement a test checks. With -strict,
// any requirement nobody proves fails the command.
package main

import (
	"bufio"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/BurntSushi/toml"
)

// id matches a requirement id; the OCR'd spec sometimes splits one with a space.
var id = regexp.MustCompile(`\b(?:ATLAS|AP)(?:-[A-Z]+)*-\d{3}\b`)

// definition matches the line that defines a requirement: "- **ATLAS-X-001.** text".
var definition = regexp.MustCompile(`^\s*[-*]\s*\*\*((?:ATLAS|AP)(?:-[A-Z]+)*-\d{3})\.\*\*\s*(.*)$`)

// Requirement is one defined requirement.
type Requirement struct {
	ID   string `json:"id"`
	File string `json:"file"`
	Text string `json:"text"`
}

// Review records a requirement checked by review rather than by a test.
type Review struct {
	Record string `toml:"record"` // where the review is recorded
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: reqs index -spec <dir> | reqs report [-strict] [-o file]")
		os.Exit(2)
	}
	root := repoRoot()
	var err error
	switch os.Args[1] {
	case "index":
		fl := flag.NewFlagSet("index", flag.ExitOnError)
		spec := fl.String("spec", os.Getenv("ATLAS_SPEC"), "the atlas-spec directory")
		_ = fl.Parse(os.Args[2:])
		err = index(*spec, filepath.Join(root, "spec", "requirements.json"))
	case "report":
		fl := flag.NewFlagSet("report", flag.ExitOnError)
		strict := fl.Bool("strict", false, "fail when any requirement is unproven")
		out := fl.String("o", "", "write the matrix as Markdown to this file")
		spec := fl.String("spec", os.Getenv("ATLAS_SPEC"), "the atlas-spec directory, for the principles table")
		_ = fl.Parse(os.Args[2:])
		err = report(root, *spec, *out, *strict)
	default:
		err = fmt.Errorf("unknown command %q", os.Args[1])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "reqs:", err)
		os.Exit(1)
	}
}

// index reads every requirement the spec defines, in its own words.
func index(spec, out string) error {
	if spec == "" {
		return errors.New("-spec (or ATLAS_SPEC) names the atlas-spec directory")
	}
	files, err := filepath.Glob(filepath.Join(spec, "*.md"))
	if err != nil {
		return err
	}
	seen := map[string]Requirement{}
	for _, f := range files {
		lines, err := readLines(f)
		if err != nil {
			return err
		}
		for _, line := range lines {
			m := definition.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			r := Requirement{ID: m[1], File: filepath.Base(f), Text: strings.TrimSpace(m[2])}
			if prev, dup := seen[r.ID]; dup && prev.Text != r.Text {
				return fmt.Errorf("%s is defined twice, differently: %s and %s", r.ID, prev.File, r.File)
			}
			seen[r.ID] = r
		}
	}
	reqs := make([]Requirement, 0, len(seen))
	for _, r := range seen {
		reqs = append(reqs, r)
	}
	sort.Slice(reqs, func(i, j int) bool { return reqs[i].ID < reqs[j].ID })
	b, err := json.MarshalIndent(reqs, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	fmt.Printf("%d requirements indexed\n", len(reqs))
	return os.WriteFile(out, append(b, '\n'), 0o644)
}

func report(root, spec, out string, strict bool) error {
	b, err := os.ReadFile(filepath.Join(root, "spec", "requirements.json"))
	if err != nil {
		return fmt.Errorf("%w (run reqs index first)", err)
	}
	var reqs []Requirement
	if err := json.Unmarshal(b, &reqs); err != nil {
		return err
	}
	known := map[string]bool{}
	for _, r := range reqs {
		known[r.ID] = true
	}
	reviews := map[string]Review{}
	if _, err := toml.DecodeFile(filepath.Join(root, "spec", "review.toml"), &reviews); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	proofs, scenarios, err := scan(root)
	if err != nil {
		return err
	}
	var unknown []string
	for _, m := range []map[string][]string{proofs, scenarios} {
		for ref := range m {
			if !known[ref] {
				unknown = append(unknown, fmt.Sprintf("%s (in %s)", ref, m[ref][0]))
			}
		}
	}
	sort.Strings(unknown)

	var md strings.Builder
	families := map[string][3]int{}
	var open []string
	md.WriteString("# Requirement matrix\n\nGenerated by `make requirements`; do not edit. A scenario proves its requirement once a conformance runner runs it (Phase 9); until then the requirement is open.\n\n| Requirement | Proved by | Scenario |\n|---|---|---|\n")
	for _, r := range reqs {
		fam := r.ID[:strings.LastIndex(r.ID, "-")]
		c := families[fam]
		scenario := "—"
		if len(scenarios[r.ID]) > 0 {
			var ids []string
			for _, f := range scenarios[r.ID] {
				ids = append(ids, strings.TrimSuffix(filepath.Base(f), ".json"))
			}
			scenario = strings.Join(ids, ", ")
		}
		switch {
		case len(proofs[r.ID]) > 0:
			c[0]++
			fmt.Fprintf(&md, "| %s | %s | %s |\n", r.ID, strings.Join(proofs[r.ID], ", "), scenario)
		case reviews[r.ID].Record != "":
			c[1]++
			fmt.Fprintf(&md, "| %s | review: %s | %s |\n", r.ID, reviews[r.ID].Record, scenario)
		default:
			c[2]++
			open = append(open, r.ID)
			fmt.Fprintf(&md, "| %s | — | %s |\n", r.ID, scenario)
		}
		families[fam] = c
	}
	names := make([]string, 0, len(families))
	for f := range families {
		names = append(names, f)
	}
	sort.Strings(names)
	tested, reviewed := 0, 0
	fmt.Println("family                         tested  review  open")
	for _, f := range names {
		c := families[f]
		tested, reviewed = tested+c[0], reviewed+c[1]
		fmt.Printf("%-30s %6d %7d %5d\n", f, c[0], c[1], c[2])
	}
	fmt.Printf("\n%d requirements: %d tested, %d by review, %d open\n", len(reqs), tested, reviewed, len(open))

	principles, err := principleGaps(spec, proofs)
	if err != nil {
		return err
	}
	for _, g := range principles {
		fmt.Println("ATLAS-PRINCIPLES-002:", g)
	}
	for _, u := range unknown {
		fmt.Println("unknown requirement named in a test:", u)
	}
	if out != "" {
		if err := os.WriteFile(out, []byte(md.String()), 0o644); err != nil {
			return err
		}
	}
	if len(unknown) > 0 {
		return fmt.Errorf("%d unknown requirement ids named in tests", len(unknown))
	}
	if strict && (len(open) > 0 || len(principles) > 0) {
		return fmt.Errorf("%d requirements open, %d principles without a tested requirement", len(open), len(principles))
	}
	return nil
}

// scan finds the requirement ids named in the repository's tests (Go test
// files and Python tests), and apart from them in the protocol's scenario
// files, which prove nothing until a runner runs them.
func scan(root string) (tests, scenarios map[string][]string, err error) {
	tests, scenarios = map[string][]string{}, map[string][]string{}
	err = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if strings.HasPrefix(name, ".") || name == "node_modules" || name == "testdata" && strings.Contains(path, "tools") {
				return filepath.SkipDir
			}
			return nil
		}
		scenario := strings.HasSuffix(name, ".json") && strings.Contains(filepath.ToSlash(path), "references/scenarios/")
		test := strings.HasSuffix(name, "_test.go") ||
			strings.HasSuffix(name, ".py") && (strings.HasPrefix(name, "test_") || strings.HasSuffix(name, "_test.py"))
		if !test && !scenario || strings.HasPrefix(filepath.ToSlash(path), filepath.ToSlash(filepath.Join(root, "tools", "reqs"))) {
			return nil
		}
		into := tests
		if scenario {
			into = scenarios
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		for _, ref := range id.FindAllString(string(b), -1) {
			if !slices.Contains(into[ref], rel) {
				into[ref] = append(into[ref], rel)
			}
		}
		return nil
	})
	return tests, scenarios, err
}

// principleGaps checks ATLAS-PRINCIPLES-002 against §6.6.1's table: each
// principle row names requirements in its "Tested by" column; at least one
// must be proven by a test. Without the spec, nothing is checked.
func principleGaps(spec string, proofs map[string][]string) ([]string, error) {
	if spec == "" {
		return nil, nil
	}
	lines, err := readLines(filepath.Join(spec, "06-6-principles.md"))
	if err != nil {
		return nil, err
	}
	var gaps []string
	row := regexp.MustCompile(`^\|\s*(\d{2})\s*\|\s*([^|]+?)\s*\|`)
	in := false
	for _, line := range lines {
		if strings.HasPrefix(line, "### ") {
			in = strings.HasPrefix(line, "### 6.6.1") // the principles table only, not 6.6.2's differences
			continue
		}
		if !in {
			continue
		}
		m := row.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		cells := strings.Split(line, "|")
		tested := cells[len(cells)-2]
		ok := false
		for _, ref := range expand(tested) {
			if len(proofs[ref]) > 0 {
				ok = true
				break
			}
		}
		if !ok {
			gaps = append(gaps, fmt.Sprintf("principle %s (%s) has no tested requirement yet", m[1], m[2]))
		}
	}
	return gaps, nil
}

// expand turns "ATLAS-RESOURCE-001 to 007, AP-DOC-003" into every id it names.
func expand(cell string) []string {
	var out []string
	span := regexp.MustCompile(`((?:ATLAS|AP)(?:-[A-Z]+)*)-(\d{3})(?:\s*(?:to|–|-)\s*(\d{3}))?((?:\s*,\s*\d{3})*)`)
	for _, m := range span.FindAllStringSubmatch(cell, -1) {
		var lo, hi int
		fmt.Sscanf(m[2], "%d", &lo)
		hi = lo
		if m[3] != "" {
			fmt.Sscanf(m[3], "%d", &hi)
		}
		for n := lo; n <= hi; n++ {
			out = append(out, fmt.Sprintf("%s-%03d", m[1], n))
		}
		for _, extra := range regexp.MustCompile(`\d{3}`).FindAllString(m[4], -1) {
			out = append(out, m[1]+"-"+extra)
		}
	}
	return out
}

func readLines(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var lines []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	return lines, sc.Err()
}

// repoRoot is the nearest parent holding go.work.
func repoRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.work")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "."
		}
		dir = parent
	}
}
